export default async function ArticlesPage({ searchParams }: { searchParams: Promise<{ id?: string }> }) {
  const { id } = await searchParams;
  const article = id ? articles.find((item) => item.id === id) : null;
  if (id && !article) notFound();

  return (
    <>
      <PageHero
        title={article?.title || "Статьи и новости"}
        description={article?.teaser || "Полезные материалы о подборе, оборудовании и аренде."}
        eyebrow={article ? "Статьи" : "Журнал NORD"}
      />
      <section className="section">
        {article
          ? <article className="container article-body"><p className="eyebrow">{article.tag} · NORD</p>{article.content}<div className="article-back"><Link className="text-link" href="/articles">← Все статьи</Link></div></article>
          : <div className="container article-grid">{articles.map((item) => <article className="article-card" key={item.id}><p className="eyebrow">{item.tag}</p><h3>{item.title}</h3><p>{item.teaser}</p><Link className="text-link" href={`/articles?id=${item.id}`}>Читать статью ↗</Link></article>)}</div>}
      </section>
    </>
  );
}
